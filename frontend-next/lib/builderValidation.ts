/**
 * builderValidation.ts
 *
 * Publish-time validation for the Showroom Studio builder.
 *
 * Rules:
 *  - A field with `required: true` must be non-empty.
 *  - For repeater fields, "non-empty" means at least one item exists.
 *  - Inside repeater items, sub-fields with `required: true` must be
 *    non-empty in every item.
 *  - The `contact` section is special: phone, email, and whatsapp are all
 *    marked required in the schema, but the rule is satisfied when AT LEAST
 *    ONE of the three has a value (OR logic, not AND logic).
 *  - Validation only runs on the Publish action — draft auto-saves are never
 *    blocked.
 *
 * Returns an array of `ValidationError` objects. An empty array means the
 * form is valid and publishing may proceed.
 */

import { getSectionType } from '@/lib/builderSections';

export interface ValidationError {
  /** The section key the error belongs to, e.g. "hero". */
  sectionKey: string;
  /** The section's display label, e.g. "Top of your page". */
  sectionLabel: string;
  /** The field key the error belongs to, e.g. "title". */
  fieldKey: string;
  /** The field's display label, e.g. "Business name". */
  fieldLabel: string;
  /** The message shown to the user. */
  message: string;
  /**
   * DOM id of the field that should receive focus when the error is clicked.
   * Matches the `id` prop generated by BuilderForm: `builder-{sectionKey}-{fieldKey}`.
   */
  fieldId: string;
  /** For repeater item errors: the 0-based index of the invalid item. */
  itemIndex?: number;
}

/**
 * Keys in the `contact` section that satisfy the "at least one" OR rule.
 * All three are marked `required` in builderSections.ts so the red asterisk
 * appears on each, but the validator only raises an error if ALL THREE are
 * empty.
 */
const CONTACT_OR_KEYS = new Set(['phone', 'email', 'whatsapp']);

function isEmpty(value: unknown): boolean {
  if (value === null || value === undefined) return true;
  if (typeof value === 'string') return value.trim().length === 0;
  if (Array.isArray(value)) return value.length === 0;
  return false;
}

/**
 * Validate all active sections against `formData`.
 *
 * @param activeSections  The ordered list of active section keys.
 * @param formData        The current form values.
 * @returns               Array of errors. Empty array = valid.
 */
export function validateBuilderForm(
  activeSections: string[],
  formData: Record<string, unknown>,
): ValidationError[] {
  const errors: ValidationError[] = [];

  for (const sectionKey of activeSections) {
    const sec = getSectionType(sectionKey);
    if (!sec) continue;

    // ── Special case: contact section uses OR logic for phone/email/whatsapp ──
    if (sectionKey === 'contact') {
      const hasContact = CONTACT_OR_KEYS.has('phone') &&
        ['phone', 'email', 'whatsapp'].some(k => !isEmpty(formData[k]));
      if (!hasContact) {
        errors.push({
          sectionKey,
          sectionLabel: sec.label,
          fieldKey: 'phone',
          fieldLabel: 'Phone / Email / WhatsApp',
          message: 'Add at least one way to reach you — phone, email, or WhatsApp.',
          fieldId: `builder-${sectionKey}-phone`,
        });
      }
      continue; // skip per-field loop for contact — handled above
    }

    // ── General per-field validation ─────────────────────────────────────────
    for (const field of sec.fields) {
      if (field.type === 'hidden' || !field.required) continue;

      const value = formData[field.key];

      if (field.type === 'repeater') {
        // Repeater: must have at least one item
        if (!Array.isArray(value) || value.length === 0) {
          errors.push({
            sectionKey,
            sectionLabel: sec.label,
            fieldKey: field.key,
            fieldLabel: field.label,
            message: field.requiredMessage ?? `Add at least one ${field.label.toLowerCase()}.`,
            fieldId: `builder-${sectionKey}-${field.key}`,
          });
          continue;
        }

        // Validate required sub-fields inside each item
        if (field.itemFields) {
          (value as Record<string, unknown>[]).forEach((item, idx) => {
            for (const sub of field.itemFields!) {
              if (!sub.required) continue;
              // image sub-fields: skip — uploading a photo is optional within an item
              if (sub.type === 'image') continue;
              if (isEmpty(item[sub.key])) {
                errors.push({
                  sectionKey,
                  sectionLabel: sec.label,
                  fieldKey: `${field.key}[${idx}].${sub.key}`,
                  fieldLabel: `${field.label} #${idx + 1} — ${sub.label}`,
                  message: sub.requiredMessage ?? `${sub.label} is required in ${field.label} #${idx + 1}.`,
                  fieldId: `${field.key}-${idx}-${sub.key}`,
                  itemIndex: idx,
                });
              }
            }
          });
        }
      } else {
        // Scalar field
        if (isEmpty(value)) {
          errors.push({
            sectionKey,
            sectionLabel: sec.label,
            fieldKey: field.key,
            fieldLabel: field.label,
            message: field.requiredMessage ?? `${field.label} is required.`,
            fieldId: `builder-${sectionKey}-${field.key}`,
          });
        }
      }
    }
  }

  return errors;
}

/**
 * Returns a deduplicated set of section keys that have at least one error.
 * Useful for highlighting section cards in the form.
 */
export function errorSectionKeys(errors: ValidationError[]): Set<string> {
  return new Set(errors.map(e => e.sectionKey));
}

/**
 * Returns a deduplicated set of field ids that have errors.
 * Useful for applying red-border styles in FieldControl.
 */
export function errorFieldIds(errors: ValidationError[]): Set<string> {
  return new Set(errors.map(e => e.fieldId));
}
