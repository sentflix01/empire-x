/**
 * lib/privateFiles.ts — storage for sensitive files (identity documents).
 *
 * Files are never served from a public URL. The database stores an opaque
 * reference "private:<key>"; viewers get a link that expires after a few
 * minutes, issued only after the caller's right to see the file is checked.
 *
 * Where files live:
 *  - Real: a private Supabase bucket — PRIVATE_SUPABASE_BUCKET, falling back to
 *    RECEIPTS_SUPABASE_BUCKET — never the public SUPABASE_BUCKET.
 *  - Demo: the already-private Demo bucket.
 *  - Local development (NODE_ENV !== 'production' and no private bucket): a
 *    folder outside the public /uploads directory (PRIVATE_UPLOAD_DIR, default
 *    "private-uploads"), served only through HMAC-signed, expiring links.
 * In production without a private bucket, storing fails closed (503).
 */
import crypto from 'crypto';
import fs from 'fs';
import path from 'path';
import { getCurrentDatabaseEnvironment } from '../db/pool';
import { getSupabaseProjectUrl, getSupabaseStorageAuthHeaders } from '../middleware/upload';

export const PRIVATE_REF_PREFIX = 'private:';
export const DEFAULT_LINK_SECONDS = 300;

const EXTENSIONS: Record<string, string> = {
  'image/jpeg': 'jpg', 'image/png': 'png', 'image/webp': 'webp',
  'image/heic': 'heic', 'image/heif': 'heif', 'application/pdf': 'pdf',
};
export const PRIVATE_FILE_MIME_TYPES = Object.keys(EXTENSIONS);

type Store =
  | { kind: 'supabase'; projectUrl: string; bucket: string; key: string }
  | { kind: 'local'; dir: string };

function supabaseStore(): Store | null {
  if (getCurrentDatabaseEnvironment() === 'demo') {
    const projectUrl = getSupabaseProjectUrl('demo');
    const bucket = process.env.DEMO_SUPABASE_BUCKET?.trim();
    const key = process.env.DEMO_SUPABASE_STORAGE_KEY;
    return projectUrl && bucket && key ? { kind: 'supabase', projectUrl, bucket, key } : null;
  }
  const projectUrl = getSupabaseProjectUrl('real');
  const bucket = (process.env.PRIVATE_SUPABASE_BUCKET ?? process.env.RECEIPTS_SUPABASE_BUCKET)?.trim();
  const key = process.env.SUPABASE_STORAGE_KEY;
  if (!projectUrl || !bucket || !key) return null;
  // Never write private files into the public site-media bucket.
  if (bucket.toLowerCase() === process.env.SUPABASE_BUCKET?.trim().toLowerCase()) return null;
  return { kind: 'supabase', projectUrl, bucket, key };
}

export function localPrivateDir(): string {
  return path.join(process.cwd(), process.env.PRIVATE_UPLOAD_DIR ?? 'private-uploads');
}

function store(): Store | null {
  const remote = supabaseStore();
  if (remote) return remote;
  if (process.env.NODE_ENV === 'production') return null;
  return { kind: 'local', dir: localPrivateDir() };
}

export function privateFilesAvailable(): boolean {
  return store() !== null;
}

export function isPrivateRef(value: unknown): value is string {
  return typeof value === 'string' && value.startsWith(PRIVATE_REF_PREFIX) && value.length > PRIVATE_REF_PREFIX.length;
}

function keyOf(ref: string): string {
  const key = ref.slice(PRIVATE_REF_PREFIX.length);
  // Keys are generated by this module: segments of safe characters only.
  if (!/^[A-Za-z0-9_-]+(\/[A-Za-z0-9_.-]+)+$/.test(key) || key.includes('..')) {
    throw Object.assign(new Error('Invalid private file reference'), { statusCode: 400 });
  }
  return key;
}

const encodeKey = (key: string) => key.split('/').map(encodeURIComponent).join('/');

function unavailable(): Error {
  return Object.assign(new Error('Private file storage is not configured'), { statusCode: 503 });
}

/** Stores the file under `<prefix>/<random>.<ext>` and returns its reference ("private:…"). */
export async function storePrivateFile(prefix: string, buffer: Buffer, mimeType: string): Promise<string> {
  if (!/^[A-Za-z0-9_-]+(\/[A-Za-z0-9_-]+)*$/.test(prefix)) throw new Error('Invalid private file prefix');
  const s = store();
  if (!s) throw unavailable();
  const key = `${prefix}/${crypto.randomUUID()}.${EXTENSIONS[mimeType] ?? 'bin'}`;
  if (s.kind === 'local') {
    const target = path.join(s.dir, ...key.split('/'));
    await fs.promises.mkdir(path.dirname(target), { recursive: true });
    await fs.promises.writeFile(target, buffer, { mode: 0o600 });
  } else {
    const response = await fetch(`${s.projectUrl}/storage/v1/object/${encodeURIComponent(s.bucket)}/${encodeKey(key)}`, {
      method: 'POST',
      headers: { ...getSupabaseStorageAuthHeaders(s.key), 'Content-Type': mimeType, 'Cache-Control': 'private, no-store', 'x-upsert': 'false' },
      body: new Uint8Array(buffer),
      signal: AbortSignal.timeout(15_000),
    });
    if (!response.ok) throw new Error(`Private file upload failed [${response.status}]`);
  }
  return PRIVATE_REF_PREFIX + key;
}

function localSigningKey(): Buffer {
  const secret = process.env.JWT_SECRET;
  if (!secret) throw unavailable();
  // A key derived for this purpose only, so a link signature is never a JWT signature.
  return crypto.createHmac('sha256', secret).update('nodbusiness-private-file-links-v1').digest();
}

function localSignature(key: string, expires: number): string {
  return crypto.createHmac('sha256', localSigningKey()).update(`${key}\n${expires}`).digest('base64url');
}

/** A link to the file that works for `expiresInSeconds`. Call only after an access check. */
export async function privateFileLink(ref: string, expiresInSeconds = DEFAULT_LINK_SECONDS): Promise<string> {
  const key = keyOf(ref);
  const s = store();
  if (!s) throw unavailable();
  if (s.kind === 'local') {
    const expires = Math.floor(Date.now() / 1000) + expiresInSeconds;
    const apiBase = (process.env.API_URL ?? 'http://localhost:3001').replace(/\/$/, '');
    return `${apiBase}/api/private-files/${encodeKey(key)}?expires=${expires}&signature=${localSignature(key, expires)}`;
  }
  const response = await fetch(`${s.projectUrl}/storage/v1/object/sign/${encodeURIComponent(s.bucket)}/${encodeKey(key)}`, {
    method: 'POST',
    headers: { ...getSupabaseStorageAuthHeaders(s.key), 'Content-Type': 'application/json' },
    body: JSON.stringify({ expiresIn: expiresInSeconds }),
    signal: AbortSignal.timeout(10_000),
  });
  if (!response.ok) throw new Error(`Could not sign private file link [${response.status}]`);
  const signed = await response.json() as { signedURL?: string; signedUrl?: string };
  const p = signed.signedURL ?? signed.signedUrl;
  if (!p) throw new Error('Storage returned no signed URL');
  return /^https:\/\//i.test(p) ? p : `${s.projectUrl}/storage/v1${p.startsWith('/') ? p : `/${p}`}`;
}

/**
 * Local development only: resolves a signed link to a file path, or null when
 * the signature is wrong, the link expired, or the file is missing.
 */
export function resolveLocalPrivateLink(key: string, expires: string | undefined, signature: string | undefined): string | null {
  const s = store();
  if (!s || s.kind !== 'local' || !expires || !signature) return null;
  let safeKey: string;
  try { safeKey = keyOf(PRIVATE_REF_PREFIX + key); } catch { return null; }
  const exp = Number(expires);
  if (!Number.isInteger(exp) || exp < Math.floor(Date.now() / 1000)) return null;
  const expected = Buffer.from(localSignature(safeKey, exp));
  const given = Buffer.from(signature);
  if (expected.length !== given.length || !crypto.timingSafeEqual(expected, given)) return null;
  const file = path.join(s.dir, ...safeKey.split('/'));
  return file.startsWith(s.dir + path.sep) && fs.existsSync(file) ? file : null;
}

/** Deletes the file. Missing files count as deleted. */
export async function deletePrivateFile(ref: string): Promise<void> {
  const key = keyOf(ref);
  const s = store();
  if (!s) throw unavailable();
  if (s.kind === 'local') {
    await fs.promises.rm(path.join(s.dir, ...key.split('/')), { force: true });
    return;
  }
  const response = await fetch(`${s.projectUrl}/storage/v1/object/${encodeURIComponent(s.bucket)}`, {
    method: 'DELETE',
    headers: { ...getSupabaseStorageAuthHeaders(s.key), 'Content-Type': 'application/json' },
    body: JSON.stringify({ prefixes: [key] }),
    signal: AbortSignal.timeout(10_000),
  });
  if (!response.ok && response.status !== 404) throw new Error(`Private file delete failed [${response.status}]`);
}
