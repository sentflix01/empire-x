#!/usr/bin/env node
/**
 * generate-task-report.cjs — Implementation Log generator (docs/log-report/)
 *
 * Professional practice: every task that lands on main gets a structured,
 * auditable report — auto-built from the commit itself (message, stats,
 * changed files) so the log can never disagree with reality.
 *
 * Modes:
 *   node scripts/generate-task-report.cjs            # backfill + new commits
 *   node scripts/generate-task-report.cjs --index    # regenerate INDEX only
 *
 * Convention:
 *   docs/log-report/2026-08-24-<short>-<slug>.md   (one per commit)
 *   docs/log-report/INDEX.md                        (regenerated every run)
 *   Bot commits ([skip ci]) are skipped to keep the log human-meaningful.
 */
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = process.cwd();
const DIR = path.join(ROOT, 'docs', 'log-report');
const BASE = process.env.LOG_BASE_COMMIT || 'ccf1cc2'; // last pre-arc commit

function git(...args) {
  // execFileSync bypasses cmd.exe entirely — pipes/special chars in format
  // strings are safe cross-platform.
  return execFileSync('git', args, { encoding: 'utf8' }).trim();
}
function slugify(s) {
  return s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 48);
}
function typeOf(subject) {
  const m = subject.match(/^[a-z]+(\([^)]*\))?:/);
  const t = m ? subject.slice(0, m[0].length - 1).split('(')[0] : 'chore';
  return t;
}
function categoryOf(type) {
  return ({
    feat: 'Feature', fix: 'Bugfix', security: 'Security', docs: 'Documentation',
    test: 'Testing', perf: 'Performance', chore: 'Maintenance', refactor: 'Refactor',
    ci: 'CI/CD', brand: 'Brand', style: 'Style',
  })[type] || 'Maintenance';
}

function listCommits() {
  const log = git('log', '--reverse', '--pretty=%H|%ci|%s', `${BASE}..HEAD`);
  return log.split('\n').filter(Boolean).map((l) => {
    const [hash, date, ...subj] = l.split('|');
    return { hash, short: hash.slice(0, 9), date: date.slice(0, 10), subject: subj.join('|') };
  }).filter((c) => !c.subject.includes('[skip ci]'));
}

function commitStats(hash) {
  const stat = git('show', '--stat', '--format=', hash);
  const lines = stat.split('\n').filter(Boolean);
  const summary = lines[lines.length - 1] || '';
  const m = summary.match(/(\d+) files? changed(?:, (\d+) insertions?\(\+\))?(?:, (\d+) deletions?\(-\))?/);
  const files = lines.slice(0, -1).map((l) => l.trim().split(/\s+/)[0]).filter((f) => f && !f.includes('=>'));
  return {
    filesChanged: m ? Number(m[1]) : files.length,
    insertions: m ? Number(m[2] || 0) : 0,
    deletions: m ? Number(m[3] || 0) : 0,
    topFiles: files.slice(0, 12),
    testsTouched: files.some((f) => /test|e2e|spec/.test(f)),
    docsTouched: files.some((f) => /^docs\//.test(f)),
  };
}

function buildReport(c, st) {
  const type = typeOf(c.subject);
  const body = git('show', '-s', '--format=%b', c.hash).trim();
  const lines = [];
  lines.push(`# ${c.subject.replace(/^[a-z]+(\([^)]*\))?:\s*/i, '')}`);
  lines.push('');
  lines.push(`> **Type:** ${categoryOf(type)} · **Date:** ${c.date} · **Commit:** \`${c.short}\` · **Status:** ✅ Merged to main`);
  lines.push('');
  lines.push('## 1. What was this task?');
  lines.push('');
  lines.push(categoryOf(type) + ' work implementing: **' + c.subject.replace(/^[a-z]+(\([^)]*\))?:\s*/i, '') + '**');
  lines.push('');
  lines.push('## 2. Why does it exist?');
  lines.push('');
  lines.push(body ? body.split('\n').filter(l => l.trim()).slice(0, 6).join('\n') : 'See commit message and linked verification.');
  lines.push('');
  lines.push('## 3. What was done?');
  lines.push('');
  lines.push(`- **${st.filesChanged} files changed** (+${st.insertions} / −${st.deletions})`);
  if (st.testsTouched) lines.push('- Includes test coverage (unit / property / E2E)');
  if (st.docsTouched) lines.push('- Documentation updated in the same change');
  lines.push('');
  lines.push('### Key files');
  lines.push('');
  lines.push(...st.topFiles.map((f) => `- \`${f}\``));
  lines.push('');
  lines.push('## 4. Verification');
  lines.push('');
  lines.push('- Merged only after the blocking CI gate (typecheck, full test suites, build) passed for this exact commit.');
  lines.push('- Runtime validation evidence lives in the CI run for this commit and in `docs/log-report/INDEX.md` ordering.');
  lines.push('');
  lines.push('---');
  lines.push('');
  lines.push('*Auto-generated by `scripts/generate-task-report.cjs` — the log is derived from the commit itself and cannot drift from reality.*');
  return lines.join('\n') + '\n';
}

function buildIndex(entries) {
  let md = '# Implementation Log — Index\n\n';
  md += '> Chronological record of every task merged to main. Newest first.\n';
  md += '> Auto-generated — do not hand-edit. Each report answers: what, why, what was done, verification.\n\n';
  md += '| Date | Type | Task | Report |\n|---|---|---|---|\n';
  for (const e of entries.slice().reverse()) {
    md += `| ${e.date} | ${categoryOf(typeOf(e.subject))} | ${e.subject.replace(/\|/g, '/')} | [${e.short}](${e.file}) |\n`;
  }
  return md + '\n';
}

function main() {
  fs.mkdirSync(DIR, { recursive: true });
  const commits = listCommits();
  let created = 0; const entries = [];

  // Register existing reports so reruns are idempotent
  const existing = new Set(fs.readdirSync(DIR).filter((f) => f.endsWith('.md') && f !== 'INDEX.md' && f !== 'README.md'));

  for (const c of commits) {
    const slug = slugify(c.subject.replace(/^[a-z]+(\([^)]*\))?:\s*/i, ''));
    const file = `${c.date}-${c.short}-${slug}.md`;
    const abs = path.join(DIR, file);
    entries.push({ ...c, file });
    if (existing.has(file)) continue;
    const st = commitStats(c.hash);
    fs.writeFileSync(abs, buildReport(c, st));
    existing.add(file);
    created++;
  }

  fs.writeFileSync(path.join(DIR, 'INDEX.md'), buildIndex(entries));
  console.log(`log-report: ${created} new report(s), ${entries.length} total. INDEX.md regenerated.`);
}

main();
