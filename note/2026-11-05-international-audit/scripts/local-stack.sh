#!/usr/bin/env bash
# Starts a fully local Nodbusiness stack for testing: Postgres + Redis + backend + frontend.
#
#   bash note/2026-11-05-international-audit/scripts/local-stack.sh up      # start (idempotent)
#   bash note/2026-11-05-international-audit/scripts/local-stack.sh status
#   bash note/2026-11-05-international-audit/scripts/local-stack.sh down
#
# Safety:
# - Every connection string points at 127.0.0.1. The repo's own guard
#   (backend/db/operationSafety.js) also refuses non-local seed targets.
# - Generated secrets and test passwords live in $NB_LOCAL_DIR/env.sh (mode 600),
#   outside the repository. Nothing here is a real credential.
# - Never source a hosted-database .env into this script.
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
NB_LOCAL_DIR="${NB_LOCAL_DIR:-$HOME/.nodbusiness-local}"
PGDATA="${NB_PGDATA:-$NB_LOCAL_DIR/pgdata}"
PGPORT="${PGPORT:-5432}"
DB_NAME="nodbusiness_audit"
DB_USER="nodbusiness"
PG_BIN="$(dirname "$(command -v pg_ctl 2>/dev/null || ls /usr/lib/postgresql/*/bin/pg_ctl | sort -V | tail -1)")"
RUN_AS=()
if [ "$(id -u)" = "0" ]; then   # Postgres refuses to run as root
  RUN_AS=(runuser -u postgres --)
  PGDATA="${NB_PGDATA:-/var/lib/postgresql/nodbusiness-local}"
fi

log() { printf '\033[36m[local-stack]\033[0m %s\n' "$*"; }

ensure_env() {
  mkdir -p "$NB_LOCAL_DIR"
  if [ ! -f "$NB_LOCAL_DIR/env.sh" ]; then
    rnd() { node -e "process.stdout.write(require('crypto').randomBytes($1).toString('hex'))"; }
    umask 077
    cat > "$NB_LOCAL_DIR/env.sh" <<EOF
# Generated by local-stack.sh — local test values only.
export NODE_ENV=development
export PORT=3001
export DATABASE_URL="postgresql://$DB_USER:$(rnd 12)@127.0.0.1:$PGPORT/$DB_NAME"
export DATABASE_URL_REQUIRE_TLS=false
export REDIS_URL="redis://127.0.0.1:6379"
export JWT_SECRET="$(rnd 48)"
export OTP_SALT="$(rnd 24)"
export FRONTEND_URL="http://localhost:3002"
export E2E_TEST_EMAIL="e2e-user@example.test"
export E2E_ADMIN_EMAIL="e2e-admin@example.test"
export E2E_TEST_PASSWORD="$(rnd 12)"
export E2E_ADMIN_PASSWORD="$(rnd 12)"
export NEXT_PUBLIC_API_BASE_URL="http://localhost:3001"
export NEXT_PUBLIC_APP_URL="http://localhost:3002"
EOF
    log "generated $NB_LOCAL_DIR/env.sh"
  fi
  # shellcheck disable=SC1091
  source "$NB_LOCAL_DIR/env.sh"
}

db_password() { node -e "process.stdout.write(decodeURIComponent(new URL(process.env.DATABASE_URL).password))"; }

start_postgres() {
  if pg_isready -h 127.0.0.1 -p "$PGPORT" -q; then log "postgres already running on $PGPORT"; else
    if [ ! -f "$PGDATA/PG_VERSION" ]; then
      mkdir -p "$PGDATA"; [ ${#RUN_AS[@]} -gt 0 ] && chown postgres:postgres "$PGDATA" && chmod 700 "$PGDATA"
      "${RUN_AS[@]}" "$PG_BIN/initdb" -D "$PGDATA" -U postgres --auth=trust -E UTF8 --locale=C.UTF-8 >/dev/null
    fi
    "${RUN_AS[@]}" "$PG_BIN/pg_ctl" -D "$PGDATA" -l "$PGDATA/postgres.log" \
      -o "-p $PGPORT -k /tmp -c listen_addresses=127.0.0.1" start </dev/null >/dev/null 2>&1
    log "postgres started on $PGPORT"
  fi
  local pw; pw="$(db_password)"
  psql -h 127.0.0.1 -p "$PGPORT" -U postgres -v ON_ERROR_STOP=1 -qtA <<SQL >/dev/null
DO \$\$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '$DB_USER') THEN
    CREATE ROLE $DB_USER LOGIN SUPERUSER PASSWORD '$pw';
  ELSE ALTER ROLE $DB_USER PASSWORD '$pw'; END IF;
END \$\$;
SQL
  psql -h 127.0.0.1 -p "$PGPORT" -U postgres -qtAc "SELECT 1 FROM pg_database WHERE datname='$DB_NAME'" | grep -q 1 \
    || createdb -h 127.0.0.1 -p "$PGPORT" -U postgres -O "$DB_USER" "$DB_NAME"
}

start_redis() {
  if redis-cli -h 127.0.0.1 ping >/dev/null 2>&1; then log "redis already running"; else
    redis-server --bind 127.0.0.1 --port 6379 --daemonize yes --save '' --appendonly no \
      --logfile "$NB_LOCAL_DIR/redis.log" </dev/null >/dev/null 2>&1
    log "redis started"
  fi
}

migrate_and_seed() {
  (cd "$REPO/backend" && npm run --silent migrate > "$NB_LOCAL_DIR/migrate.log" 2>&1) \
    || { log "migrations failed — see $NB_LOCAL_DIR/migrate.log"; exit 1; }
  log "migrations applied ($(grep -c . "$NB_LOCAL_DIR/migrate.log") log lines)"
  (cd "$REPO/backend" && ALLOW_E2E_SEED=1 npm run --silent seed:e2e > "$NB_LOCAL_DIR/seed.log" 2>&1) \
    || { log "seed failed — see $NB_LOCAL_DIR/seed.log"; exit 1; }
  log "e2e test accounts seeded"
}

wait_http() { for _ in $(seq 1 "${3:-90}"); do curl -fsS -o /dev/null "$1" 2>/dev/null && return 0; sleep 1; done; log "$2 did not answer at $1"; return 1; }

start_apps() {
  if ! curl -fsS -o /dev/null http://127.0.0.1:3001/health 2>/dev/null; then
    (cd "$REPO/backend" && exec setsid npm run dev) > "$NB_LOCAL_DIR/backend.log" 2>&1 < /dev/null &
    echo $! > "$NB_LOCAL_DIR/backend.pid"
  fi
  wait_http http://127.0.0.1:3001/health backend 120 && log "backend up: http://localhost:3001/health"
  if ! curl -fsS -o /dev/null http://127.0.0.1:3002 2>/dev/null; then
    (cd "$REPO/frontend-next" && exec setsid npm run dev) > "$NB_LOCAL_DIR/frontend.log" 2>&1 < /dev/null &
    echo $! > "$NB_LOCAL_DIR/frontend.pid"
  fi
  wait_http http://127.0.0.1:3002/landing frontend 240 && log "frontend up: http://localhost:3002"
}

status() {
  pg_isready -h 127.0.0.1 -p "$PGPORT" || true
  redis-cli -h 127.0.0.1 ping 2>/dev/null || echo "redis: down"
  curl -fsS http://127.0.0.1:3001/health 2>/dev/null | head -c 400 || echo "backend: down"; echo
  curl -fsS -o /dev/null -w 'frontend: HTTP %{http_code}\n' http://127.0.0.1:3002/landing 2>/dev/null || echo "frontend: down"
}

down() {
  for svc in frontend backend; do
    [ -f "$NB_LOCAL_DIR/$svc.pid" ] && { kill -- -"$(cat "$NB_LOCAL_DIR/$svc.pid")" 2>/dev/null || pkill -P "$(cat "$NB_LOCAL_DIR/$svc.pid")" 2>/dev/null || true; rm -f "$NB_LOCAL_DIR/$svc.pid"; }
  done
  redis-cli -h 127.0.0.1 shutdown nosave 2>/dev/null || true
  [ -f "$PGDATA/PG_VERSION" ] && "${RUN_AS[@]}" "$PG_BIN/pg_ctl" -D "$PGDATA" stop -m fast >/dev/null 2>&1 || true
  log "stopped (data kept in $NB_LOCAL_DIR; delete it for a clean start)"
}

case "${1:-up}" in
  up) ensure_env; start_postgres; start_redis; migrate_and_seed; start_apps; status ;;
  status) ensure_env; status ;;
  down) ensure_env; down ;;
  *) echo "usage: $0 up|status|down"; exit 2 ;;
esac
