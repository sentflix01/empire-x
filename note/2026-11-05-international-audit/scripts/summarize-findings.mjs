#!/usr/bin/env node
/**
 * Builds SUMMARY.md from findings/*.json so counts and tables can never drift
 * from the findings themselves. Run after validate-findings.mjs.
 *
 *   node note/2026-11-05-international-audit/scripts/summarize-findings.mjs
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const all = readdirSync(join(root, 'findings')).filter((f) => f.endsWith('.json')).sort()
  .map((f) => JSON.parse(readFileSync(join(root, 'findings', f), 'utf8')));

const ORDER = ['Critical', 'High', 'Medium', 'Low', 'Info'];
const issues = all.filter((f) => f.status !== 'POSITIVE');
const count = (list, key, val) => list.filter((f) => f[key] === val).length;
const esc = (s) => String(s).replace(/\|/g, '\\|');

const lines = [
  '# Findings summary',
  '',
  '> Generated by `scripts/summarize-findings.mjs` — do not edit by hand.',
  '',
  `**${all.length} findings:** ${ORDER.map((s) => `${count(issues, 'severity', s)} ${s}`).join(' · ')} · ` +
    `${count(all, 'status', 'POSITIVE')} positive · ${count(all, 'status', 'UNVERIFIED')} unverified`,
  '',
  '## Issues by severity',
  '',
  '| ID | Severity | Kind | Area | Title | Status | CVSS v4.0 | Effort |',
  '|---|---|---|---|---|---|---|---|',
];
for (const f of issues.sort((a, b) => ORDER.indexOf(a.severity) - ORDER.indexOf(b.severity) || a.id.localeCompare(b.id))) {
  lines.push(`| ${f.id} | ${f.severity} | ${f.kind} | ${f.phase} | ${esc(f.title)} | ${f.status} | ${f.cvss_v4 ? f.cvss_v4.score : '—'} | ${f.effort} |`);
}
lines.push('', '## Positive findings (keep these from regressing)', '', '| ID | Area | Title |', '|---|---|---|');
for (const f of all.filter((x) => x.status === 'POSITIVE')) lines.push(`| ${f.id} | ${f.phase} | ${esc(f.title.replace(/^Positive: /, ''))} |`);
lines.push('');
writeFileSync(join(root, 'SUMMARY.md'), lines.join('\n'));
console.log(`SUMMARY.md written: ${all.length} findings`);
